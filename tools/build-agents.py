#!/usr/bin/env python3
"""Render agents/<name>.md from agents/templates/<name>.md plus the shared
jordan-core block (RULINGS R8).

Each template carries its own frontmatter and hand-written body, with one
placeholder line, `<!-- jordan-core:insert -->`, where the shared block goes.
The block is read from agents/shared/jordan-core.md, between
`<!-- jordan-core:begin -->` and `<!-- jordan-core:end -->` (markers
included), so the JORDAN discipline is written once and is byte-identical in
every rendered agent. Every template in the directory is rendered; there is no
list to keep in step, so an agent made by new-agent.py needs no registration.

The rendered file also gets one YAML comment as the last frontmatter line,
saying it is generated. A YAML comment costs the agent no context; an HTML
comment in the body would ride into every spawn.

Usage:
    build-agents.py                 write every agents/<name>.md
    build-agents.py <name>...       write only the named agents
    build-agents.py --check         write nothing; exit 1 and list the files
                                    that are stale, missing, or generated
                                    from a template that no longer exists

Stdlib only.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATES_DIR = ROOT / "agents" / "templates"
OUT_DIR = ROOT / "agents"
SHARED = ROOT / "agents" / "shared" / "jordan-core.md"

BEGIN_MARKER = "<!-- jordan-core:begin -->"
END_MARKER = "<!-- jordan-core:end -->"
INSERT_MARKER = "<!-- jordan-core:insert -->"
BLOCK_CAP = 1200  # bytes between the markers, R8
GENERATED_PREFIX = "# generated by tools/build-agents.py from agents/templates/"
GENERATED_SUFFIX = "; edit the template, not this file"


class BuildError(Exception):
    """A template or the shared file cannot be rendered."""


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def shared_block(text: str) -> str:
    """The shared block, markers included."""
    try:
        start = text.index(BEGIN_MARKER)
        end = text.index(END_MARKER, start) + len(END_MARKER)
    except ValueError:
        raise BuildError(
            f"{SHARED}: missing {BEGIN_MARKER} / {END_MARKER} marker pair"
        ) from None
    return text[start:end]


def block_size(block: str) -> int:
    """Bytes of block content, markers excluded: what the cap measures."""
    return len(block[len(BEGIN_MARKER):-len(END_MARKER)].encode("utf-8"))


def template_names() -> list:
    return sorted(p.stem for p in TEMPLATES_DIR.glob("*.md"))


def render(name: str, block: str) -> str:
    """One rendered agent file: template with the block spliced in and the
    generated comment added to the frontmatter."""
    path = TEMPLATES_DIR / f"{name}.md"
    if not path.exists():
        raise BuildError(f"{path}: no such template")
    text = read(path)
    if INSERT_MARKER not in text:
        raise BuildError(f"{path}: missing {INSERT_MARKER}")
    lines = text.split("\n")
    if lines[0] != "---" or "---" not in lines[1:]:
        raise BuildError(f"{path}: no frontmatter between --- lines")
    close = lines.index("---", 1)
    lines.insert(close, f"{GENERATED_PREFIX}{name}.md{GENERATED_SUFFIX}")
    return "\n".join(lines).replace(INSERT_MARKER, block, 1)


def stale_files(block: str) -> list:
    """(path, reason) for every rendered file a fresh build would change."""
    problems = []
    names = template_names()
    for name in names:
        out = OUT_DIR / f"{name}.md"
        try:
            rendered = render(name, block)
        except BuildError as exc:
            problems.append((out, str(exc)))
            continue
        if not out.exists():
            problems.append((out, "missing"))
        elif read(out) != rendered:
            problems.append((out, "stale"))
    for out in sorted(OUT_DIR.glob("*.md")):
        if out.stem not in names and GENERATED_PREFIX in read(out):
            problems.append((out, "generated, but its template is gone"))
    return problems


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    check = "--check" in argv
    wanted = [a for a in argv if not a.startswith("-")]
    unknown = [a for a in argv if a.startswith("-") and a != "--check"]
    if unknown:
        print(f"build-agents.py: unknown option {unknown[0]}", file=sys.stderr)
        return 2
    try:
        block = shared_block(read(SHARED))
        if check:
            problems = stale_files(block)
            if problems:
                print("STALE (run tools/build-agents.py to fix):")
                for path, reason in problems:
                    print(f"  {path.relative_to(ROOT)}: {reason}")
                return 1
            print(f"OK: {len(template_names())} rendered agent files current")
            return 0
        for name in wanted or template_names():
            out = OUT_DIR / f"{name}.md"
            out.write_text(render(name, block), encoding="utf-8")
            print(f"wrote {out.relative_to(ROOT)}")
    except (BuildError, OSError) as exc:
        print(f"build-agents.py: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
